import assert from 'node:assert/strict';
import * as r from '../app/js/rules.js';
const d = 'Kartons\n- [ ] A\n- [x] B\n- [ ] C';
assert.equal(r.moveChecklistLine(d, 3, null), 'Kartons\n- [ ] C\n- [ ] A\n- [x] B');
assert.equal(r.moveChecklistLine(d, 1, 3), 'Kartons\n- [x] B\n- [ ] C\n- [ ] A');
assert.equal(r.moveChecklistLine(d, 1, 1), d);
assert.equal(r.moveChecklistLineToEnd(d, 2), 'Kartons\n- [ ] A\n- [ ] C\n- [x] B');
assert.equal(r.addDoneStamp('Text', new Date(2026, 10, 8)), 'Text\n✓ 08.11.2026');
assert.equal(r.addDoneStamp('Text\n✓ 01.11.2026', new Date(2026, 10, 8)), 'Text\n✓ 01.11.2026');
assert.equal(r.removeDoneStamp('Text\n✓ 08.11.2026'), 'Text');
assert.equal(r.removeDoneStamp('✓ 08.11.2026'), '');
assert.equal(r.setRecurrence('Text\n✓ 08.11.2026', 'weekly'), 'Text\n🔁 wöchentlich\n✓ 08.11.2026');
assert.equal(r.setRecurrence('Text\n🔁 täglich', null), 'Text');
assert.equal(r.getRecurrence('x\n🔁 Wöchentlich'), 'weekly');
assert.equal(r.getRecurrence('🔁 every 2 weeks'), 'biweekly');
assert.equal(r.getRecurrence('nichts'), null);
const today = new Date(2026, 10, 8);
assert.equal(r.nextDue('2026-11-08', 'daily', today), '2026-11-09');
assert.equal(r.nextDue('2026-11-01', 'daily', today), '2026-11-09');
assert.equal(r.nextDue('2026-11-03', 'weekly', today), '2026-11-10');
assert.equal(r.nextDue('2026-01-31', 'monthly', new Date(2026, 0, 31)), '2026-02-28');
assert.equal(r.nextDue(null, 'monthly', today), '2026-12-08');
assert.equal(r.nextDue('2024-02-29', 'yearly', new Date(2024, 1, 29)), '2025-02-28');
assert.equal(r.resetForRepeat('- [x] A\n- [ ] B\n🔁 wöchentlich\n✓ 08.11.2026'), '- [ ] A\n- [ ] B\n🔁 wöchentlich');
// Verschieben: was die Ziel-Liste nicht speichern kann
const all = { dueDate: true, dueDatetime: true, description: true };
const none = { dueDate: false, dueDatetime: false, description: false };
assert.deepEqual(r.moveLosses({ due: null, description: null }, none), []);
assert.deepEqual(r.moveLosses({ due: '2026-11-20', description: 'x' }, all), []);
assert.deepEqual(r.moveLosses({ due: '2026-11-20', description: '  ' }, none), ['date']);
assert.deepEqual(r.moveLosses({ due: '2026-11-20T09:30:00', description: null }, { ...all, dueDatetime: false }), ['time']);
assert.deepEqual(r.moveLosses({ due: '2026-11-20T09:30:00', description: 'x' }, none), ['date', 'description']);
assert.deepEqual(r.moveLosses({ due: null, description: '- [ ] A' }, { ...all, description: false }), ['description']);
