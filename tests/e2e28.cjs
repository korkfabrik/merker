const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const BASE = 'http://localhost:8123';
const APP = `${BASE}/local/merker/index.html`;
const calls = async () => (await fetch(`${BASE}/__mock/calls`)).json();
const items = async (e) => (await fetch(`${BASE}/__mock/items?entity=${e}`)).json();
const ok = (n) => console.log('OK  ', n);
const pad = (n) => String(n).padStart(2, '0');
const iso = (d) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
const plus = (days) => { const d = new Date(); d.setDate(d.getDate() + days); return iso(d); };
const deDate = (d = new Date()) => d.toLocaleDateString('de-DE', { day: '2-digit', month: '2-digit', year: 'numeric' });
(async () => {
  const browser = await chromium.launch();
  const page = await (await browser.newContext({ locale: 'de-DE', viewport: { width: 390, height: 860 } })).newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  const waitCall = async (n, service, pred = () => true) => {
    for (let i = 0; i < 60; i++) {
      const found = (await calls()).slice(n).filter((c) => c.service === service && pred(c));
      if (found.length) return found;
      await page.waitForTimeout(100);
    }
    throw new Error(`kein ${service}`);
  };
  const closed = () => page.waitForSelector('.sheet-root', { state: 'detached' });
  await page.goto(APP);
  await page.waitForSelector('.list-tile');
  await page.goto(`${APP}#/liste/todo.einkaufsliste`);
  await page.waitForSelector('li.swipe');

  // A. Lange drücken / Rechtsklick: neues Datum
  await page.locator('li.swipe', { hasText: 'Milch' }).click({ button: 'right' });
  await page.waitForSelector('.sheet .pick-row');
  assert.deepEqual(await page.locator('.sheet .pick-name').allInnerTexts(), ['Heute', 'Morgen', 'Wochenende', 'Nächste Woche', 'Datum wählen …', 'Kein Datum']);
  assert.match(await page.locator('.sheet .pick-row', { hasText: 'Wochenende' }).locator('.pick-count').innerText(), /Sa\./);
  assert.match(await page.locator('.sheet .pick-title').innerText(), /„Milch“ fällig am/);
  let n = (await calls()).length;
  await page.locator('.sheet .pick-row', { hasText: 'Morgen' }).click();
  let c = (await waitCall(n, 'update_item'))[0];
  assert.deepEqual([c.data.item, c.data.due_date], ['u2', plus(1)]);
  await page.waitForFunction(() => /Fällig: Morgen/.test(document.querySelector('.snackbar').textContent));
  await closed();
  n = (await calls()).length;
  await page.locator('.snackbar-action').click();
  c = (await waitCall(n, 'update_item'))[0];
  assert.equal(c.data.due_date, plus(0));
  ok('Rechtsklick/langes Drücken: Datum Morgen gesetzt, Rückgängig stellt Heute wieder her');

  // B. Erledigt-Datum
  n = (await calls()).length;
  await page.locator('li.swipe', { hasText: 'Brot' }).locator('.item-check').click();
  c = (await waitCall(n, 'update_item'))[0];
  assert.deepEqual([c.data.status, c.data.description], ['completed', `✓ ${deDate()}`]);
  n = (await calls()).length;
  await page.locator('.snackbar-action').click();
  c = (await waitCall(n, 'update_item'))[0];
  assert.deepEqual([c.data.status, c.data.description], ['needs_action', null]);
  ok('Erledigen setzt "✓ Datum" in die Beschreibung, Wieder-Öffnen nimmt es weg');

  // C. Wiederholen
  await page.waitForTimeout(400);
  await page.locator('li.swipe', { hasText: 'Brot' }).click();
  await page.waitForSelector('.sheet .recur-btn');
  assert.equal(await page.locator('.sheet .recur-btn').innerText(), 'Wiederholen');
  await page.waitForTimeout(600);
  const rb = await page.locator('.sheet .recur-btn').boundingBox();
  const dl = await page.locator('.sheet label[for=sheet-due]').boundingBox();
  assert.ok(Math.abs((rb.y + rb.height / 2) - (dl.y + dl.height / 2)) < 8, 'Knopf in der Zeile von Fälligkeit');
  await page.locator('.sheet .recur-btn').click();
  await page.waitForSelector('.pick-row');
  assert.deepEqual(await page.locator('.pick-row .pick-name').allInnerTexts(), ['Nie', 'täglich', 'wöchentlich', 'alle 2 Wochen', 'monatlich', 'jährlich']);
  await page.locator('.pick-row', { hasText: /^wöchentlich/ }).click();
  await page.waitForFunction(() => document.querySelectorAll('.sheet-root').length === 1);
  assert.equal(await page.locator('.sheet .recur-btn').innerText(), 'wöchentlich');
  n = (await calls()).length;
  await page.locator('.sheet-head-edit button[type=submit]').click();
  await closed();
  c = (await waitCall(n, 'update_item'))[0];
  assert.equal(c.data.description, '🔁 wöchentlich');
  await page.waitForTimeout(300);
  await page.locator('li.swipe', { hasText: 'Brot' }).click();
  await page.waitForSelector('.sheet .recur-btn');
  assert.equal(await page.locator('.sheet .recur-btn').innerText(), 'wöchentlich');
  assert.equal(await page.locator('.sheet textarea').inputValue(), '');
  await page.keyboard.press('Escape');
  await closed();
  n = (await calls()).length;
  await page.locator('li.swipe', { hasText: 'Brot' }).locator('.item-check').click();
  const add = (await waitCall(n, 'add_item'))[0];
  assert.deepEqual([add.data.item, add.data.due_date, add.data.description], ['Brot', plus(7), '🔁 wöchentlich']);
  const upd = (await calls()).slice(n).find((x) => x.service === 'update_item');
  assert.deepEqual([upd.data.status, upd.data.description], ['completed', `🔁 wöchentlich\n✓ ${deDate()}`]);
  await page.waitForFunction(() => /Erledigt\. Nächste Runde:/.test(document.querySelector('.snackbar').textContent));
  await page.waitForFunction(() => !document.querySelector('[data-uid^="tmp-"]'));
  n = (await calls()).length;
  await page.locator('.snackbar-action').click();
  await waitCall(n, 'remove_item');
  await waitCall(n, 'update_item', (x) => x.data.status === 'needs_action');
  for (let i = 0; i < 30 && (await items('todo.einkaufsliste')).filter((x) => x.summary === 'Brot').length !== 1; i++) await page.waitForTimeout(100);
  const brot = (await items('todo.einkaufsliste')).filter((x) => x.summary === 'Brot');
  assert.equal(brot.length, 1);
  assert.deepEqual([brot[0].status, brot[0].description], ['needs_action', '🔁 wöchentlich']);
  await page.goto(APP);
  await page.waitForSelector('.list-tile');
  await page.waitForFunction(() => document.querySelectorAll('.due-list li.swipe').length > 0);
  await page.goto(`${APP}#/liste/todo.einkaufsliste`);
  await page.waitForSelector('li.swipe');
  const brotRow = page.locator('#content > ul li.swipe', { hasText: 'Brot' }).first();
  assert.equal(await brotRow.locator('.repeat-mark').count(), 1);
  assert.equal(await brotRow.locator('.repeat-mark').getAttribute('aria-label'), 'Wiederholt sich wöchentlich');
  assert.ok(!(await brotRow.innerText()).includes('🔁'));
  await fetch(`${BASE}/__mock/add-item?entity=todo.haushalt&summary=Blumen%20gie%C3%9Fen&due=${plus(0)}&desc=${encodeURIComponent('🔁 täglich')}`, { method: 'POST' });
  await page.goto(APP);
  await page.waitForSelector('.list-tile');
  const homeRow = page.locator('.due-list li.swipe', { hasText: 'Blumen gießen' });
  await homeRow.waitFor();
  assert.equal(await homeRow.locator('.repeat-mark').count(), 1);
  await page.goto(`${APP}#/liste/todo.einkaufsliste`);
  await page.waitForSelector('li.swipe');
  ok('Wiederholen: Auswahl speichert "🔁 wöchentlich", Erledigen legt nächste Runde in 7 Tagen an, Rückgängig räumt auf');

  // D. Unteraufgaben ordnen, Erledigte nach unten
  await fetch(`${BASE}/__mock/add-item?entity=todo.einkaufsliste&summary=Umzug9&desc=${encodeURIComponent('Kartons\n- [ ] A\n- [ ] B\n- [ ] C')}`, { method: 'POST' });
  await page.locator('li.swipe', { hasText: 'Umzug9' }).click();
  await page.waitForSelector('.sub-handle');
  await page.waitForTimeout(400);
  const hC = await page.locator('.sub-swipe', { hasText: 'C' }).locator('.sub-handle').boundingBox();
  const rA = await page.locator('.sub-swipe', { hasText: 'A' }).boundingBox();
  n = (await calls()).length;
  await page.mouse.move(hC.x + hC.width / 2, hC.y + hC.height / 2);
  await page.mouse.down();
  for (let i = 1; i <= 12; i++) await page.mouse.move(hC.x + hC.width / 2, hC.y + hC.height / 2 - ((hC.y - rA.y + 10) * i) / 12);
  await page.mouse.up();
  c = (await waitCall(n, 'update_item'))[0];
  assert.equal(c.data.description, 'Kartons\n- [ ] C\n- [ ] A\n- [ ] B');
  ok('Unteraufgabe per Griff nach oben gezogen');
  await page.keyboard.press('Escape');
  await closed();
  await page.evaluate(() => localStorage.setItem('merker.subDoneLast', 'true'));
  await page.waitForTimeout(300);
  await page.locator('li.swipe', { hasText: 'Umzug9' }).click();
  await page.waitForSelector('.sub-handle');
  n = (await calls()).length;
  await page.locator('.check-row', { hasText: 'C' }).click();
  c = (await waitCall(n, 'update_item'))[0];
  assert.equal(c.data.description, 'Kartons\n- [ ] A\n- [ ] B\n- [x] C');
  ok('Mit Einstellung rutscht eine abgehakte Unteraufgabe ans Ende');
  await page.keyboard.press('Escape');
  await closed();

  // E. Duplizieren
  await page.waitForTimeout(300);
  await page.locator('li.swipe', { hasText: 'Milch' }).click();
  await page.waitForSelector('.sheet button[aria-label=Duplizieren]');
  assert.deepEqual(await page.locator('.sheet-actions-right button').evaluateAll((els) => els.map((e) => e.getAttribute('aria-label'))), ['Erledigt', 'Verschieben', 'Duplizieren', 'Teilen']);
  await page.locator('.sheet button[aria-label=Duplizieren]').click();
  await page.waitForSelector('.pick-row');
  assert.deepEqual(await page.locator('.pick-row .pick-name').allInnerTexts(), ['Einkaufsliste', 'Haushalt']);
  n = (await calls()).length;
  await page.locator('.pick-row', { hasText: 'Haushalt' }).click();
  c = (await waitCall(n, 'add_item'))[0];
  assert.deepEqual([c.target.entity_id, c.data.item, c.data.description, c.data.due_date], ['todo.haushalt', 'Milch', 'Fettarm, 1 Liter', plus(0)]);
  await page.waitForFunction(() => /Kopie in Haushalt angelegt/.test(document.querySelector('.snackbar').textContent));
  await closed();
  for (let i = 0; i < 30 && !(await items('todo.haushalt')).some((x) => x.summary === 'Milch'); i++) await page.waitForTimeout(100);
  await page.waitForTimeout(300);
  n = (await calls()).length;
  await page.locator('.snackbar-action').click();
  await waitCall(n, 'remove_item');
  for (let i = 0; i < 30 && (await items('todo.haushalt')).some((x) => x.summary === 'Milch'); i++) await page.waitForTimeout(100);
  assert.ok(!(await items('todo.haushalt')).some((x) => x.summary === 'Milch'));
  ok('Duplizieren: Ziel-Liste wählbar, Kopie mit Beschreibung und Datum, Rückgängig entfernt sie');

  // F. Neue Aufgabe mit Wiederholen
  await page.locator('#fab').click();
  await page.waitForSelector('.sheet .recur-btn');
  await page.locator('.sheet input[name=title]').fill('Filter wechseln');
  await page.locator('.sheet .recur-btn').click();
  await page.locator('.pick-row', { hasText: 'monatlich' }).click();
  await page.waitForFunction(() => document.querySelectorAll('.sheet-root').length === 1);
  n = (await calls()).length;
  await page.locator('.sheet button[type=submit]').click();
  c = (await waitCall(n, 'add_item'))[0];
  assert.deepEqual([c.data.item, c.data.description], ['Filter wechseln', '🔁 monatlich']);
  ok('Neue Aufgabe mit Wiederholen monatlich');
  // Escape in der Auswahl schließt nur die Auswahl
  await page.waitForSelector('.sheet-root', { state: 'detached' });
  await page.locator('#fab').click();
  await page.waitForSelector('.sheet .recur-btn');
  await page.locator('.sheet .recur-btn').click();
  await page.waitForSelector('.pick-row');
  await page.keyboard.press('Escape');
  await page.waitForFunction(() => document.querySelectorAll('.sheet-root').length === 1 && !document.querySelector('.pick-row'));
  await page.waitForTimeout(400);
  assert.equal(await page.locator('.sheet input[name=title]').count(), 1);
  ok('Escape in der Wiederholen-Auswahl lässt den Dialog offen');
  await page.keyboard.press('Escape');
  await closed();

  // G. Erscheinungsbild
  await page.goto(`${APP}#/einstellungen/darstellung`);
  await page.waitForSelector('.seg-bar');
  const seg = page.locator('.seg-bar[aria-label=Erscheinungsbild] .seg-btn');
  assert.deepEqual(await seg.allInnerTexts(), ['Gerät', 'Hell', 'Dunkel']);
  assert.equal(await seg.nth(0).getAttribute('aria-pressed'), 'true');
  await seg.nth(2).click();
  assert.equal(await page.evaluate(() => document.documentElement.dataset.theme), 'dark');
  assert.equal(await seg.nth(2).getAttribute('aria-pressed'), 'true');
  assert.equal(await page.evaluate(() => getComputedStyle(document.body).backgroundColor), 'rgb(18, 19, 22)');
  await page.reload();
  await page.waitForSelector('.seg-bar');
  assert.equal(await page.evaluate(() => document.documentElement.dataset.theme), 'dark');
  await page.locator('.seg-bar .seg-btn', { hasText: 'Gerät' }).click();
  assert.equal(await page.evaluate(() => document.documentElement.dataset.theme ?? null), null);
  assert.notEqual(await page.evaluate(() => getComputedStyle(document.body).backgroundColor), 'rgb(18, 19, 22)');
  ok('Erscheinungsbild Dunkel fest gewählt, bleibt nach Neuladen, zurück auf Gerät');

  assert.deepEqual(errors, []);
  await browser.close();
})().catch((e) => { console.log('FEHLER:', e); process.exit(1); });
