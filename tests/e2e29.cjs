const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const APP = 'http://localhost:8123/local/merker/index.html';
const ok = (n) => console.log('OK  ', n);
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ locale: 'de-DE', viewport: { width: 390, height: 860 }, hasTouch: true, isMobile: true });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  const cdp = await ctx.newCDPSession(page);
  await page.goto(APP);
  await page.waitForSelector('.list-tile');
  await page.goto(`${APP}#/liste/todo.einkaufsliste`);
  await page.waitForSelector('li.swipe');
  const box = await page.locator('li.swipe', { hasText: 'Milch' }).boundingBox();
  const p = { x: box.x + box.width / 2, y: box.y + box.height / 2 };
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [p] });
  await page.waitForTimeout(800);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await page.waitForSelector('.sheet .pick-row');
  await page.waitForTimeout(300);
  assert.match(page.url(), /#\/liste\/todo\.einkaufsliste$/);
  assert.equal(await page.locator('.sheet-head-edit').count(), 0);
  ok('Langes Drücken mit dem Finger öffnet die Datumsauswahl, nicht den Dialog');
  await page.keyboard.press('Escape');
  await page.waitForSelector('.sheet-root', { state: 'detached' });
  await page.waitForTimeout(900);
  await page.locator('li.swipe', { hasText: 'Milch' }).tap();
  await page.waitForSelector('.sheet-head-edit');
  ok('Kurzes Tippen öffnet weiter den Bearbeiten-Dialog');
  assert.deepEqual(errors, []);
  await browser.close();
})().catch((e) => { console.log('FEHLER:', e); process.exit(1); });
